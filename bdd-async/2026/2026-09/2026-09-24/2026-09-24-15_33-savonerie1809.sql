CREATE OR REPLACE VIEW TRANSFERTSTOCKDETAILSCPL AS 
  SELECT
    t.ID ,
    t.IDTRANSFERTSTOCK ,
    t2.DESIGNATION AS IDTRANSFERTSTOCKLIB,
    t.IDPRODUIT ,
    p.libelle AS IDPRODUITLIB,
    CAST(t.QUANTITE AS NUMBER(30,5)) AS QUANTITE,
    CAST(t.PU AS NUMBER(30, 5)) AS PU,
    t.idsource,
    t.COMPTELOCALISATIONDEPART,
    l1.LIBELLE AS compteLocalisationDepartLib,
    t.COMPTELOCALISATIONARRIVEE,
    l2.LIBELLE AS compteLocalisationArriveelib
FROM TRANSFERTSTOCKDETAILS t
         LEFT JOIN TRANSFERTSTOCK t2 ON t2.ID = t.IDTRANSFERTSTOCK
         LEFT JOIN AS_INGREDIENTS  p ON p.ID = t.IDPRODUIT
         LEFT JOIN LOCALISATION l1 ON t.COMPTELOCALISATIONDEPART = l1.ID 
         LEFT JOIN LOCALISATION l2 ON t.COMPTELOCALISATIONARRIVEE = l2.ID;