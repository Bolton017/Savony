ALTER TABLE MVTSTOCK ADD remarque VARCHAR2(255);

CREATE OR REPLACE FORCE VIEW MVTSTOCKLIB ("ID", "DESIGNATION", "IDMAGASIN", "IDOBJET", "IDMAGASINLIB", "IDVENTE", "IDVENTELIB", "IDTRANSFERT", "IDTRANSFERTLIB", "IDTYPEMVSTOCK", "IDTYPEMVSTOCKLIB", "DATY", "ETAT", "ETATLIB", "IDRESERVATION", "MONTANTENTREE", "MONTANTSORTIE", "MOTSCLESSS","REMARQUE") AS 
  SELECT
m.ID ,
m.DESIGNATION ,
m.IDMAGASIN ,
m.IDOBJET ,
m2.VAL  AS idMagasinlib,
m.IDVENTE ,
v.DESIGNATION  AS idVentelib,
m.IDTRANSFERT ,
CAST('' AS VARCHAR2(255)) AS idTransfertlib,
m.IDTYPEMVSTOCK ,
t.VAL AS idTypeMvStocklib ,
m.DATY ,
m.ETAT ,
CASE
 WHEN m.ETAT = 0
 THEN 'ANNUL&Eacute;E'
 WHEN m.ETAT = 1
 THEN 'CR&Eacute;&Eacute;E'
 WHEN m.ETAT = 11
 THEN 'VALID&Eacute;E'
END AS etatlib,
v.IDRESERVATION,
gm.montantEntree,
gm.montantSortie,
  (
        m.DESIGNATION || ' ' ||
        NVL(m2.VAL, '') || ' ' ||
        NVL(v.DESIGNATION, '') || ' ' ||
        TO_CHAR(m.DATY, 'YYYY-MM-DD')
    ) AS motsClesss,
 m.remarque
FROM MVTSTOCK m
LEFT JOIN TYPEMVTSTOCK t ON t.ID = m.IDTYPEMVSTOCK
LEFT JOIN VENTE v ON v.ID = m.IDVENTE
LEFT JOIN MAGASIN2 m2 ON m2.ID = m.IDMAGASIN
left join mvtStockFilleGroupeMere gm on gm.IDMVTSTOCK=m.ID
