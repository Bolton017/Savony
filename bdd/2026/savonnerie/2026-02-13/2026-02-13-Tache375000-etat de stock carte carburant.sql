CREATE OR REPLACE VIEW as_ingredients_lib_with_stock as
SELECT
    ing.id,
    ing.LIBELLE,
    ing.PARFUMS,
    ing.SEUIL,
    ing.unite,
    ing.QUANTITEPARPACK,
    ing.pu,
    ing.ACTIF,
    ing.PHOTO,
    ing.CALORIE,
    ing.DURRE,
    ing.COMPOSE,
    ing.COMPOSELIB,
    ing.IDCATEGORIEINGREDIENT,
    ing.CATEGORIEINGREDIENT,
    ing.idcategorie,
    ing.idfournisseur,
    ing.daty,
    ing.bienOuServ,
    ing.etatlib,
    ing.COMPTE_VENTE,
    ing.COMPTE_ACHAT,
    ing.pv,
    ing.tva,
    ing.TYPESTOCK,
    ing.idunite,
    ing.REFPOST,
    ing.REFQUALIFICATION,
    ing.REFPOSTLIB,
    ing.REFQUALIFICATIONLIB,
    ing.idfamilleLib,
    SUM(eing.ENTREE) AS ENTREE,
    SUM(eing.SORTIE) AS SORTIE,
    SUM(eing.RESTE) AS RESTE
FROM AS_INGREDIENTS_LIB ing
         LEFT JOIN V_ETATSTOCK_ING eing ON eing.id = ing.ID
GROUP BY
    ing.id,
    ing.LIBELLE,
    ing.PARFUMS,
    ing.SEUIL,
    ing.unite,
    ing.QUANTITEPARPACK,
    ing.pu,
    ing.ACTIF,
    ing.PHOTO,
    ing.CALORIE,
    ing.DURRE,
    ing.COMPOSE,
    ing.COMPOSELIB,
    ing.IDCATEGORIEINGREDIENT,
    ing.CATEGORIEINGREDIENT,
    ing.idcategorie,
    ing.idfournisseur,
    ing.daty,
    ing.bienOuServ,
    ing.etatlib,
    ing.COMPTE_VENTE,
    ing.COMPTE_ACHAT,
    ing.pv,
    ing.tva,
    ing.TYPESTOCK,
    ing.idunite,
    ing.REFPOST,
    ing.REFQUALIFICATION,
    ing.REFPOSTLIB,
    ing.REFQUALIFICATIONLIB,
    ing.idfamilleLib;