create view V_STOCK_DASHBOARD as
SELECT
    v."ID",v."IDPRODUIT",v."IDPRODUITLIB",v."CATEGORIEINGREDIENT",v."IDTYPEPRODUITLIB",v."IDMAGASIN",v."IDMAGASINLIB",v."QUANTITE",v."ENTREE",v."SORTIE",v."RESTE",v."UNITE",v."IDUNITELIB",v."PU",v."DATY"
    (RESTE * PU) AS valeurStock,
    CAST(SUM(QUANTITE) OVER () AS number(30,2))  AS nbArticles
FROM V_ETATSTOCK_ENTREE v
/

