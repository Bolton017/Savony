CREATE TABLE ANALYSE
   (	
    "ID" VARCHAR2(255), 
	"DATY" DATE, 
	"IDFABRICATION" VARCHAR2(400), 
	"IDCRITERE" VARCHAR2(400), 
	"VALEUR" NUMBER(30,2),
	"IDRESPONSABLE" VARCHAR2(400), 
	"ETAT" NUMBER(38,0) DEFAULT 1 NOT NULL ENABLE, 
	 FOREIGN KEY ("IDCRITERE") REFERENCES CRITERE("ID"),
	 FOREIGN KEY ("IDFABRICATION") REFERENCES FABRICATION("ID"),
	 FOREIGN KEY ("IDRESPONSABLE") REFERENCES LOG_PERSONNEL("ID")
   );

CREATE SEQUENCE SEQ_ANALYSE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;
CREATE OR REPLACE FUNCTION GET_SEQ_ANALYSE
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
    SELECT SEQ_ANALYSE.NEXTVAL INTO retour FROM DUAL;
    RETURN retour;
END;
 
 
CREATE OR REPLACE VIEW ANALYSECPL AS
SELECT
    a.ID,
    a.IDCRITERE,
    a.IDFABRICATION,
    a.VALEUR,
    a.IDRESPONSABLE,
    a.ETAT,
    -- Libellés des références
    c.val AS IDCRITERELIB,               
    f.LIBELLE AS IDFABRICATIONLIB,         
    p.NOM || ' ' || p.PRENOM AS IDRESPONSABLELIB, 
   CASE
        WHEN f.ETAT=1
            THEN 'CRÉÉ'
        WHEN f.ETAT=11
            THEN 'VALIDÉ'
        WHEN f.ETAT=0
            THEN 'ANNULÉ'
        END AS ETATLIB
FROM ANALYSE a
LEFT JOIN CRITERE c ON a.IDCRITERE = c.ID
LEFT JOIN FABRICATION f ON a.IDFABRICATION = f.ID
LEFT JOIN LOG_PERSONNEL p ON a.IDRESPONSABLE = p.ID;


CREATE OR REPLACE VIEW CRITEREPRODUITLIB AS
SELECT
    a.ID,
    a.IDCRITERE,
    a.idtypeproduit,
    c.val AS IDCRITERELIB,               
 	tp.val AS idtypeproduitlib
FROM critereproduit a
LEFT JOIN CRITERE c ON a.IDCRITERE = c.ID
LEFT JOIN typeproduit tp ON a.idtypeproduit = tp.ID
;

