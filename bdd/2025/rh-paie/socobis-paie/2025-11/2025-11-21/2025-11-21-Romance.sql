CREATE OR REPLACE VIEW PAIE_PERS_ELTPAIE_LIB_AV
(
    "ID", "MATRICULE", "ID_CODE_RUBRIQUE", "CODE_RUBRIQUE",
    "DATE_DEBUT", "DATE_FIN", "GAIN", "RETENUE", "REMARQUE",
    "IDPERSONNEL", "ETAT", "ID_OBJET", "IDUSER",
    "MOISREGULARISATION", "ANNEEREGULARISATION",
    "IDCATEGORIE_QUALIFICATION", "IDFONCTION",
    "POURCENTAGE",
    "MOISREGULARISATIONLIB"
) AS
SELECT
    pp."ID",
    pp."MATRICULE",
    pp."ID_CODE_RUBRIQUE",
    pp."CODE_RUBRIQUE",
    pp."DATE_DEBUT",
    pp."DATE_FIN",
    pp."GAIN",
    pp."RETENUE",
    pp."REMARQUE",
    pp."IDPERSONNEL",
    pp."ETAT",
    pp."ID_OBJET",
    pp."IDUSER",
    pp."MOISREGULARISATION",
    pp."ANNEEREGULARISATION",
    pp."IDCATEGORIE_QUALIFICATION",
    pp."IDFONCTION",
    pp."POURCENTAGE",
    -- Libellé du mois
    TO_CHAR(TO_DATE(pp.MOISREGULARISATION, 'MM'), 'MONTH', 'NLS_DATE_LANGUAGE=FRENCH')
        AS MOISREGULARISATIONLIB
FROM PAIE_PERS_ELTPAIE_LIB2 pp
WHERE pp.ID_CODE_RUBRIQUE = 'PRU0447';
