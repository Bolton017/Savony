CREATE VIEW AS_BCFILLECALC (ID, PRODUIT, IDBC, PU, TVA, UNITE, REMISE, IDDEVISE, TAUXDECHANGE, DESIGNATION, QUANTITE, MONTANT, MONTANTDELAREMISE, MONTANTREMISE, MONTANTTVA, MONTANTTTC, MONTANTHT, MONTANTTTCAR) AS 
  select 
       bcf.ID,
       bcf.PRODUIT,
       bcf.IDBC,
       bcf.PU,
       bcf.TVA,
       bcf.UNITE,
       bcf.REMISE,
       bcf.IDDEVISE,
       bcf.TAUXDECHANGE,
       bcf.DESIGNATION,
       nvl(bcf.QUANTITE,0) AS QUANTITE,
       cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2))                                                                                   AS montant,
       cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2))                                                          as montantdelaremise,
       CAST(cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2)) -  cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2)) AS NUMBER(30,2) )  montantremise,
       CAST ((cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2)) -  cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2))) * (bcf.tva/100) AS NUMBER(30,2)) AS montanttva,
       CAST( (cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2)) -  cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2)))  + (CAST ((cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2)) -  cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2))) * (bcf.tva/100) AS NUMBER(30,2)) ) AS NUMBER(30,2)) AS montantttc,
       CAST (bcf.quantite * bcf.pu + (bcf.quantite * bcf.pu  * (bcf.tva/100)) - bcf.quantite * bcf.pu * (bcf.tva/100) AS NUMBER(30,2)) AS montantht,
       cast( CAST( (cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2)) -  cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2)))  + (CAST ((cast(NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0) as Number(30, 2)) -  cast(((NVL(bcf.PU, 0) * NVL(bcf.QUANTITE, 0)) * (bcf.REMISE / 100)) as number(30, 2))) * (bcf.tva/100) AS NUMBER(30,2)) ) AS NUMBER(30,2)) * nvl(TAUXDECHANGE,1)as number(30,2)) as montantttcAr
from AS_BONDECOMMANDE_FILLE bcf;

