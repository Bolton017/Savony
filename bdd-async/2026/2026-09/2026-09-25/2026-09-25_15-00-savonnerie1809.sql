CREATE OR REPLACE FORCE VIEW DEMTRANSFILLEGROUPEMERE ("IDDEMANDETRANSFERT", "MONTANTQUANTITE") AS
select f.IDDEMANDETRANSFERT,cast(sum(nvl(f.pu*f.QUANTITE,0)) as number(30,2)) as montantQuantite
from DEMANDETRANSFERTFILLE f group by f.IDDEMANDETRANSFERT;

CREATE OR REPLACE VIEW DEMANDETRANSFERTCPL AS
SELECT
    t.ID ,
    t.DESIGNATION ,
    t.IDMAGASINDEPART ,
    m.VAL AS IDMAGASINDEPARTLIB,
    t.IDMAGASINARRIVE ,
    m2.VAL AS IDMAGASINARRIVELIB,
    t.DATY ,
    t.ETAT ,
    t.idof,
    t.CATEGORIEINGREDIENT,
    CAST(dfg.montantQuantite AS NUMBER(30,2)) AS montantQuantite,
    c.VAL  AS CATEGORIEINGREDIENTLIB,
    m.IDDEPARTEMENT AS IDDEPARTEMENTDEPART,
    s.LIBELLE AS idDepartementLibDepart,
    m2.IDDEPARTEMENT AS IDDEPARTEMENTARRIVE,
    s2.LIBELLE AS idDepartementLibArrive,
    CASE
        WHEN t.ETAT = 0
            THEN 'ANNULEE'
        WHEN t.ETAT = 1
            THEN 'Cr&eacute;&eacute;'
        WHEN t.ETAT = 11
            THEN 'Vis&eacute;'
        END AS ETATLIB
FROM demandetransfert t
         LEFT JOIN MAGASINPOINT m ON m.ID = t.IDMAGASINDEPART
         LEFT JOIN MAGASINPOINT m2 ON m2.ID = t.IDMAGASINARRIVE
         LEFT JOIN CATEGORIEINGREDIENT c ON c.ID = t.CATEGORIEINGREDIENT
         LEFT JOIN SERVICE s ON m.IDDEPARTEMENT = s.ID
         LEFT JOIN SERVICE s2 ON m2.IDDEPARTEMENT = s2.ID
         LEFT JOIN DEMTRANSFILLEGROUPEMERE dfg ON dfg.IDDEMANDETRANSFERT = t.id
;
