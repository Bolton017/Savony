CREATE OR REPLACE VIEW V_RESULTAT_BESOINS_PAR_MATIERE AS
SELECT
    CAST(NULL AS VARCHAR2(50))   AS ID,
    CAST(NULL AS VARCHAR2(50))   AS ID_MATIERE,
    CAST(NULL AS VARCHAR2(255))  AS ID_MATIERE_LIB,
    CAST(NULL AS VARCHAR2(255))  AS UNITELIB,
    CAST(NULL AS NUMBER(15,6))   AS QUANTITE_BESOINS
FROM dual
WHERE 1 = 0;