CREATE TABLE ZONECLIENT (
    ID VARCHAR2(250) PRIMARY KEY,
    VAL VARCHAR2(250),
    DESCE VARCHAR2(250)
);

CREATE TABLE FORFAITZONECLIENT (
    ID VARCHAR2(250) PRIMARY KEY,
    ETAT NUMBER,
    IDZONE VARCHAR2(250),
    IDINGREDIENT VARCHAR2(250),
    TARIF NUMBER(32,5),
    DATY DATE,

    CONSTRAINT FK_FZONECLIENT_ZONE
        FOREIGN KEY (IDZONE)
        REFERENCES ZONECLIENT(ID),
    CONSTRAINT FK_FZONECLIENT_INGREDIENT
        FOREIGN KEY (IDINGREDIENT)
        REFERENCES AS_INGREDIENTS(ID)
);

CREATE OR REPLACE VIEW FORFAITZONECLIENTLIB AS
SELECT f.*, z.VAL AS IDZONELIB, ing.LIBELLE AS IDINGREDIENTLIB FROM FORFAITZONECLIENT f
LEFT JOIN ZONECLIENT z ON z.ID = f.IDZONE
LEFT JOIN AS_INGREDIENTS ing ON ing.ID = f.IDINGREDIENT;

CREATE SEQUENCE seqzoneclient INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;

CREATE OR REPLACE FUNCTION getseqzoneclient
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT seqzoneclient.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;

