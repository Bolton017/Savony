
CREATE OR REPLACE  VIEW PRODUIT_FINI_ACTIF ("ID", "LIBELLE", "PARFUMS", "SEUIL", "UNITE", "QUANTITEPARPACK", "PU", "ACTIF", "PHOTO", "CALORIE", "DURRE", "COMPOSE", "COMPOSELIB", "IDCATEGORIEINGREDIENT", "CATEGORIEINGREDIENT", "IDCATEGORIE", "IDFOURNISSEUR", "DATY", "BIENOUSERV", "ETATLIB", "COMPTE_VENTE", "COMPTE_ACHAT", "PV", "TVA", "TYPESTOCK", "IDUNITE", "REFPOST", "REFQUALIFICATION", "REFPOSTLIB", "REFQUALIFICATIONLIB", "IDFAMILLELIB", "MOTSCLESSS") AS
SELECT
    "ID",
    "LIBELLE",
    "PARFUMS",
    "SEUIL",
    "UNITE",
    "QUANTITEPARPACK",
    "PU",
    "ACTIF",
    "PHOTO",
    "CALORIE",
    "DURRE",
    "COMPOSE",
    "COMPOSELIB",
    "IDCATEGORIEINGREDIENT",
    "CATEGORIEINGREDIENT",
    "IDCATEGORIE",
    "IDFOURNISSEUR",
    "DATY",
    "BIENOUSERV",
    "ETATLIB",
    "COMPTE_VENTE",
    "COMPTE_ACHAT",
    "PV",
    "TVA",
    "TYPESTOCK",
    "IDUNITE",
    "REFPOST",
    "REFQUALIFICATION",
    "REFPOSTLIB",
    "REFQUALIFICATIONLIB",
    "IDFAMILLELIB",
    UPPER(
            NVL(id, '') || ' ' ||
            NVL(libelle, '') || ' ' ||
            NVL(parfums, '') || ' ' ||
            NVL(unite, '') || ' ')
        AS MOTSCLESSS
FROM
    AS_INGREDIENTS_LIB ail
WHERE
    ail.IDCATEGORIEINGREDIENT = 'CAT008'
  AND ail.ACTIF = 1
;