CREATE TABLE directionmagasin
(
  id VARCHAR2(100) PRIMARY KEY,
  idMagasin VARCHAR2(255), 
  idDirection VARCHAR2(255),
  CONSTRAINT unique_mag_dir UNIQUE (idMagasin, idDirection)
);

CREATE SEQUENCE SEQDIRECTIONMAGASIN INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;

CREATE OR REPLACE FUNCTION GETSEQDIRECTIONMAGASIN
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQDIRECTIONMAGASIN.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;

