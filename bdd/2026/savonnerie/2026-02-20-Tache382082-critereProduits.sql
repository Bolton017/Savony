CREATE TABLE CritereProduit
   (	
    "ID" VARCHAR2(255), 
	"IDCRITERE" VARCHAR2(400), 
	"IDTYPEPRODUIT" VARCHAR2(400), 
	 FOREIGN KEY ("IDCRITERE") REFERENCES CRITERE("ID"),
	 FOREIGN KEY ("IDTYPEPRODUIT") REFERENCES TYPEPRODUIT("ID")
   );

CREATE SEQUENCE SEQ_CritereProduit INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;
CREATE OR REPLACE FUNCTION GET_SEQ_CritereProduit
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
    SELECT SEQ_CritereProduit.NEXTVAL INTO retour FROM DUAL;
    RETURN retour;
END;
 
 
