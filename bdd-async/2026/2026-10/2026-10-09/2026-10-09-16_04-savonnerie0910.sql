CREATE TABLE EVALUATION_ANNUELLE 
   (	ID VARCHAR2(100) PRIMARY KEY, 
	IDPERSONNEL VARCHAR2(100), 
	ANNEE NUMBER(*,0), 
	NOTEGLOBALE NUMBER(30,2), 
	COMMENTAIRE VARCHAR2(1000), 
	ETAT NUMBER(*,0)
);

CREATE TABLE TYPE_COMPETENCES_FP 
   (	ID VARCHAR2(50) PRIMARY KEY, 
	VAL VARCHAR2(255), 
	DESCE VARCHAR2(255)
);

CREATE TABLE EVALUATION_DETAIL 
   (	ID VARCHAR2(100) PRIMARY KEY, 
	IDEVALUATION VARCHAR2(100), 
	IDCRITERE VARCHAR2(100), 
	NOTE NUMBER(30,2), 
	COMMENTAIRE VARCHAR2(1000), 
	IDTYPECOMPETENCEFP VARCHAR2(255), 
	COMPETENCE VARCHAR2(4000), 
	AUTOEVALUATION NUMBER, 
	EVALUATIONSUPERIEUR NUMBER, 
	SYNTHESE NUMBER, 
	APPRECIATION VARCHAR2(4000), 
	REMARQUE VARCHAR2(4000), 
	CONSTRAINT FK_EVALD_EVALANUELLE FOREIGN KEY (IDEVALUATION)
	  REFERENCES EVALUATION_ANNUELLE (ID), 
	 CONSTRAINT FK_EVALD_TYPECOMPETENCE FOREIGN KEY (IDTYPECOMPETENCEFP)
	  REFERENCES TYPE_COMPETENCES_FP (ID) 
);

CREATE SEQUENCE SEQ_EVALUATION_ANNUELLE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;
CREATE SEQUENCE SEQ_EVALUATION_DETAIL INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;
CREATE SEQUENCE SEQ_TYPE_COMPETENCES_FP INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;

CREATE OR REPLACE FUNCTION GETSEQ_EVALUATION_ANNUELLE
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQ_EVALUATION_ANNUELLE.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;
CREATE OR REPLACE FUNCTION GETSEQ_EVALUATION_DETAIL
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQ_EVALUATION_DETAIL.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;

CREATE OR REPLACE FUNCTION GETSEQ_TYPE_COMPETENCES_FP
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQ_TYPE_COMPETENCES_FP.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;

CREATE VIEW EVALUATION_ANNUELLE_LIB (ID, IDPERSONNEL, IDPERSONNELLIB, MATRICULE, IDFONCTION, IDFONCTIONLIB, ANNEE, NOTEGLOBALE, COMMENTAIRE, ETAT, ETATLIB) AS 
  SELECT
    ea.ID,
    ea.IDPERSONNEL,
    lp.NOM || ' ' || lp.PRENOM AS IDPERSONNELLIB,
    pip.MATRICULE AS MATRICULE,
    pip.IDFONCTION AS IDFONCTION,
    pf.VAL AS IDFONCTIONLIB,
    ea.ANNEE,
    ea.NOTEGLOBALE,
    ea.COMMENTAIRE,
    ea.ETAT,
    CASE
        WHEN ea.ETAT = 1 THEN 'En cours'
        WHEN ea.ETAT = 11 THEN 'Terminée'
        WHEN ea.ETAT = 0 THEN 'ANNULÉE'
        END AS ETATLIB
FROM EVALUATION_ANNUELLE ea
         LEFT JOIN LOG_PERSONNEL_V2 lp
                   ON ea.IDPERSONNEL = lp.ID
         LEFT JOIN PAIE_INFO_PERSONNEL pip
                   ON ea.IDPERSONNEL = pip.ID
         LEFT JOIN PAIE_FONCTION pf
                   ON pip.IDFONCTION = pf.ID;

