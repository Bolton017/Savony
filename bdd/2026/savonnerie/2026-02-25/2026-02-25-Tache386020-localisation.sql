CREATE TABLE localisation 
   (	"ID" VARCHAR2(50) NOT NULL ENABLE, 
	"COMPTE" VARCHAR2(100), 
	"LIBELLE" VARCHAR2(200), 
	"TYPECOMPTE" VARCHAR2(255), 
	"CLASSY" VARCHAR2(50),
	 PRIMARY KEY ("ID"));

CREATE SEQUENCE SEQ_localisation
 INCREMENT BY 1 MINVALUE 10000 MAXVALUE 999999999999999999999999999
  NOCYCLE NOCACHE NOORDER;

CREATE OR REPLACE FUNCTION get_SEQ_localisation
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQ_localisation.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;
