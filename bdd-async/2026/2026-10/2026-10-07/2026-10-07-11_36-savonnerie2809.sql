create sequence seqPrj
    minvalue 1
    maxvalue 999999999999
    start with 1
    increment by 1
    cache 20;

CREATE OR REPLACE FUNCTION getSeqPrj
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
    SELECT seqPrj.NEXTVAL INTO retour FROM DUAL;

    RETURN retour;
END;
 

