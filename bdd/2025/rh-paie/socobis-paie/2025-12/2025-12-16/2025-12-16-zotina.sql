CREATE TABLE POINTAGECANTINE
(
    ID           VARCHAR2(50) NOT NULL PRIMARY KEY,
    IDPERSONNEL  VARCHAR2(50),
    DATY         DATE,
    ETAT         NUMBER(2),
    CONSTRAINT fk_pointagecantine_personnel FOREIGN KEY (IDPERSONNEL) 
        REFERENCES PAIE_INFO_PERSONNEL(ID)
);

CREATE SEQUENCE seqPtgCantine;

CREATE FUNCTION getSeqPtgCantine RETURN NUMBER IS 
    retour NUMBER;
BEGIN
    SELECT seqPtgCantine.NEXTVAL INTO retour FROM DUAL;
    RETURN retour;
END;


CREATE OR REPLACE VIEW POINTAGECANTINE_CPL as 
select 
pc.*, 
LOG.NOM || ' ' || LOG.PRENOM AS NOMPERSONNEL 
from POINTAGECANTINE pc
LEFT JOIN LOG_PERSONNEL LOG ON log.id = pc.IDPERSONNEL ;