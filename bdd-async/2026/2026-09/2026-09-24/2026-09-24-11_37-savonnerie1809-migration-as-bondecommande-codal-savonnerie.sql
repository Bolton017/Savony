            NVL(ab.DESIGNATION, '') || ' ' ||
            NVL(ab.REFERENCE, '') || ' ' ||
            NVL(ab.REMARQUE, '') || ' ' ||
            NVL(F.NOM, '') || ' ' ||
            NVL(mp.VAL, '') || ' ' ||
            NVL(m.VAL, '') || ' ' ||
            NVL(d.val, '') || ' ' ||
