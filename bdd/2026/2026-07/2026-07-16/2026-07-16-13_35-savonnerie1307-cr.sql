CREATE OR REPLACE VIEW FACTUREFOURNISSEUR_RECAP_JOUR AS
WITH BORNES AS (
    SELECT
        MIN(TRUNC(DATY)) AS DATE_MIN,
        TRUNC(SYSDATE) AS DATE_MAX
    FROM FACTUREFOURNISSEURCPL_TOUS
),
CALENDRIER AS (
    SELECT
        DATE_MIN + LEVEL - 1 AS DATY
    FROM BORNES
    CONNECT BY LEVEL <= DATE_MAX - DATE_MIN + 1
),
FACTURE_JOUR AS (
    SELECT
        TRUNC(DATY) AS DATY,
        SUM(NVL(MONTANTTTC,0)) AS MONTANTTTC,
        SUM(NVL(MONTANTPAYE,0)) AS MONTANTPAYE,
        SUM(NVL(MONTANTRESTE,0)) AS MONTANTRESTE,
        COUNT(*) AS NOMBRE
    FROM FACTUREFOURNISSEURCPL_TOUS
    GROUP BY TRUNC(DATY)
)
SELECT
    c.DATY,
    CAST(NVL(f.MONTANTTTC,0) AS NUMBER(30,5)) AS MONTANTTTC,
    CAST(NVL(f.MONTANTPAYE,0) AS NUMBER(30,5)) AS MONTANTPAYE,
    CAST(NVL(f.MONTANTRESTE,0) AS NUMBER(30,5)) AS MONTANTRESTE,
    CAST(NVL(f.NOMBRE,0) AS NUMBER(10,0)) AS NOMBRE,

    CAST(
            SUM(NVL(f.MONTANTRESTE,0))
        OVER (
                ORDER BY c.DATY
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
                )
        AS NUMBER(30,5)
    ) AS MONTANTRESTEACEJOUR

FROM CALENDRIER c
         LEFT JOIN FACTURE_JOUR f
                   ON c.DATY = f.DATY;

CREATE OR REPLACE VIEW VENTE_RECAP_JOUR AS
WITH BORNES AS (
    SELECT
        MIN(TRUNC(DATY)) AS DATE_MIN,
        TRUNC(SYSDATE) AS DATE_MAX
    FROM VENTE_CPL
),
CALENDRIER AS (
    SELECT
        DATE_MIN + LEVEL - 1 AS DATY
    FROM BORNES
    CONNECT BY LEVEL <= DATE_MAX - DATE_MIN + 1
),
VENTE_JOUR AS (
    SELECT
        TRUNC(DATY) AS DATY,
        SUM(NVL(MONTANTTTC,0)) AS MONTANTTTC,
        SUM(NVL(MONTANTPAYE,0)) AS MONTANTPAYE,
        SUM(NVL(MONTANTRESTE,0)) AS MONTANTRESTE,
        COUNT(*) AS NOMBRE
    FROM VENTE_CPL
    GROUP BY TRUNC(DATY)
)
SELECT
    c.DATY,

    CAST(NVL(v.MONTANTTTC,0) AS NUMBER(30,5)) AS MONTANTTTC,
    CAST(NVL(v.MONTANTPAYE,0) AS NUMBER(30,5)) AS MONTANTPAYE,
    CAST(NVL(v.MONTANTRESTE,0) AS NUMBER(30,5)) AS MONTANTRESTE,
    CAST(NVL(v.NOMBRE,0) AS NUMBER(10,0)) AS NOMBRE,

    CAST(
            SUM(NVL(v.MONTANTRESTE,0))
        OVER (
                ORDER BY c.DATY
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
                )
        AS NUMBER(30,5)
    ) AS MONTANTRESTEACEJOUR

FROM CALENDRIER c
         LEFT JOIN VENTE_JOUR v
                   ON c.DATY = v.DATY;