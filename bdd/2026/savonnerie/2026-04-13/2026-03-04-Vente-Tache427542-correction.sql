CREATE OR REPLACE  VIEW AS_BC_FILLE_AVEC_PRIX (ID, PRODUIT, NUMBL, QUANTITE, IDVENTEDETAIL, UNITE, IDBC_FILLE, PU, TVA, COMPTE_VENTE, COMPTE_ACHAT) AS 
  SELECT
    bl.ID,bl.PRODUIT,bl.NUMBL,bl.QUANTITE,bl.IDVENTEDETAIL,bl.UNITE,bl.IDBC_FILLE,
    CAST(ai.PU AS NUMBER(20, 2)) AS pu,
    CAST(ai.TVA AS NUMBER(20, 2)) AS tva,
    ai.COMPTE_VENTE,ai.COMPTE_ACHAT
FROM
    AS_BONDELIVRAISON_CLIENT_FILLE bl
LEFT JOIN AS_INGREDIENTS ai
    ON ai.ID = bl.PRODUIT
 
 ;
 
