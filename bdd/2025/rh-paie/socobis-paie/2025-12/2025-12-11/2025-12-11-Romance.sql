CREATE OR REPLACE VIEW CATEGORIE_QUALIFICATION_VW AS
SELECT 
    cq.ID,
    cq.IDCATEGORIE,
    cp.DESCE AS CATEGORIE_LIBELLE,
    cq.IDQUALIFICATION,
    qp.DESCE AS QUALIFICATION_LIBELLE,
    cq.REMARQUE,
    cq.ETAT,
    cq.MONTANT,
    cq.DATE_DEBUT,
    cq.DATE_FIN,
    cq.AVENANT,
    cq.IDPOSTE,
    cq.INDICE
FROM CATEGORIE_QUALIFICATION cq
LEFT JOIN CATEGORIE_PAIE cp 
       ON cq.IDCATEGORIE = cp.ID
LEFT JOIN QUALIFICATION_PAIE qp 
       ON cq.IDQUALIFICATION = qp.ID;