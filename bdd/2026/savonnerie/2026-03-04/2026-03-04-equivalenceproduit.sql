CREATE TABLE EQUIVALENCEPRODUIT
(
    ID              VARCHAR(255) not null primary key,
    IDPRODUITBASE  VARCHAR(255),
    IDPRODUITEQ    VARCHAR(255),
    UNITE           VARCHAR(255),
    QUANTITE        NUMBER(30,10)
);

CREATE SEQUENCE SEQ_EQUIVALENCEPRODUIT INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

create OR REPLACE FUNCTION getSeqEQUIVALENCEPRODUIT
    RETURN NUMBER IS
    retour NUMBER;
BEGIN
SELECT SEQ_EQUIVALENCEPRODUIT.nextval INTO retour FROM dual;
return retour;
END;