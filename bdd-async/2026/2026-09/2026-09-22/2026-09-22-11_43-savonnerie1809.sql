CREATE OR REPLACE  VIEW MVTSTOCKFILLELIB2 (ID, IDMVTSTOCK, IDPRODUIT, IDPRODUITLIB, ENTREE, SORTIE, IDVENTEDETAIL, IDVENTEDETAILLIB, IDTRANSFERTDETAIL, IDTRANSFERTDETAILLIB, DATY, IDMAGASIN, IDMAGASINLIB, PU, MONTANT, LIBELLE, MVTSRC, LIBELLEEXACTE, DATESQL, IDOBJET, IDTYPEMVSTOCK, ETAT, ETATLIB, IDUNITELIB, REMARQUE,compteLocalisation) AS 
  SELECT
    m.ID ,
    m.IDMVTSTOCK ,
    m.IDPRODUIT ,
    p.libelle  AS IDPRODUITLIB,
    m.ENTREE ,
    m.SORTIE ,
    m.IDVENTEDETAIL ,
    '' AS IDVENTEDETAILLIB,
    m.IDTRANSFERTDETAIL ,
    '' AS IDTRANSFERTDETAILLIB,
    m2.DATY ,
    m2.IDMAGASIN ,
    m3.VAL AS IDMAGASINLIB,
    m.pu,
    cast(m.pu*m.ENTREE+(m.pu*m.sortie) as number(20,5)) as montant,
    p.LIBELLE,
    m.MVTSRC,
    p.libelle AS libelleexacte,
    m2.DATY AS dateSql,
    m2.idobjet,
    m2.IDTYPEMVSTOCK,
    m2.etat,
    CASE
        WHEN m2.ETAT = 1 THEN 'CR&Eacute;&Eacute;E'
        WHEN m2.ETAT = 11 THEN 'VIS&Eacute;E'
        WHEN m2.ETAT = 11 THEN 'ANNUL&Eacute;E'
        END    AS ETATLIB,
    au.VAL AS idUniteLib,
    m.remarque AS remarque ,
    m.compteLocalisation
FROM MVTSTOCKFILLE m
         LEFT JOIN AS_INGREDIENTS  p ON p.ID = m.IDPRODUIT
         LEFT JOIN MVTSTOCK m2 ON m2.ID = m.IDMVTSTOCK
         LEFT JOIN MAGASIN2 m3 ON m3.ID = m2.IDMAGASIN
         LEFT JOIN AS_UNITE au ON au.ID = p.UNITE
 ;