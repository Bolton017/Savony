create or replace view ST_INGVENTEPOS_STANDARD_SAV as
SELECT
    ai.ID,
    ai.LIBELLE AS LIBELLE,
    ai.SEUIL,
    ai.UNITE,
    ai.QUANTITEPARPACK,
    ai.PU,
    ai.ACTIF,
    ai.PHOTO,
    ai.CALORIE,
    ai.DURRE,
    ai.COMPOSE,
    ai.CATEGORIEINGREDIENT,
    ai.IDFOURNISSEUR,
    ai.DATY,
    ai.QTELIMITE,
    tarif.PRIXUNITAIRE as PV,
    ai.LIBELLEVENTE,
    ai.SEUILMIN,
    ai.SEUILMAX,
    ai.PUACHATUSD,
    ai.PUACHATEURO,
    ai.PUACHATAUTREDEVISE,
    ai.PUVENTEUSD,
    ai.PUVENTEEURO,
    ai.PUVENTEAUTREDEVISE,
    ai.ISVENTE,
    ai.ISACHAT,
    ai.COMPTE_VENTE,
    ai.COMPTE_ACHAT,
    ai.TVA,
    1 AS TAUX,
    ai.COMPTE_VENTE AS COMPTE,
    ai.LIBELLE || ' ' || ai.COULEUR || ' ' || ai.TAILLE AS LIBELLECOMPOSANT,
    ai.COULEUR,
    ai.CODEBARRE,
    ai.REFERENCE,
    ai.CODEGROS,
    ai.PVGROS,
    u.VAL AS UNITELIB,
    CONCAT(CONCAT(ai.LIBELLE, ' - '), u.VAL) AS DESIGNATION,
    ai.TYPESTOCK,
    CAST(tarif.PRIXUNITAIRE * (1 + ai.TVA / 100) AS NUMBER(30,2)) AS PVTVA,
    CAST(tarif.PRIXUNITAIRE * (1 + ai.TVA / 100) AS NUMBER(30,2)) AS montantTTC
FROM AS_INGREDIENTS ai
         LEFT JOIN AS_RECETTE ar
                   ON ar.IDPRODUITS = ai.ID
         LEFT JOIN AS_INGREDIENTS cps
                   ON cps.ID = ar.IDINGREDIENTS
         LEFT JOIN AS_UNITE u
                   ON ai.UNITE = u.ID
         LEFT JOIN TARIF_INGREDIENTS_MAX tarif ON tarif.IDINGREDIENT = ai.id
WHERE ai.ACTIF = 1 and tarif.IDTYPECLIENT='TYPE009'
GROUP BY
    ai.ID,
    ai.LIBELLE,
    ai.SEUIL,
    ai.UNITE,
    ai.QUANTITEPARPACK,
    ai.PU,
    ai.ACTIF,
    ai.PHOTO,
    ai.CALORIE,
    ai.DURRE,
    ai.COMPOSE,
    ai.CATEGORIEINGREDIENT,
    ai.IDFOURNISSEUR,
    ai.DATY,
    ai.QTELIMITE,
    ai.PV,
    ai.LIBELLEVENTE,
    ai.SEUILMIN,
    ai.SEUILMAX,
    ai.PUACHATUSD,
    ai.PUACHATEURO,
    ai.PUACHATAUTREDEVISE,
    ai.PUVENTEUSD,
    ai.PUVENTEEURO,
    ai.PUVENTEAUTREDEVISE,
    ai.ISVENTE,
    ai.ISACHAT,
    ai.COMPTE_VENTE,
    ai.COMPTE_ACHAT,
    ai.TVA,
    ai.COULEUR,
    ai.TAILLE,
    ai.CODEBARRE,
    ai.REFERENCE,
    ai.CODEGROS,
    ai.PVGROS,
    u.VAL,
    ai.TYPESTOCK,
    tarif.PRIXUNITAIRE ;

