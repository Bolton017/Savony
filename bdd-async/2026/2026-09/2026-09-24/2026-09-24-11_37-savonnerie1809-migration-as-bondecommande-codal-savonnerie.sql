    c.NOM || ' ' || bc.REMARQUE || ' ' || bc.DESIGNATION AS motsClesss,
    bc.NUMEROBC,
    bc.IDREPRESENTANT,bc.IDDEVISE,
    r.VAL as idrepresentantLib,cast(bcf.montantHT as number(30,2)) as montantHT,
    cast(bcf.MONTANTTTC as number(30,2)) as MONTANTTTC,cast(bcf.montantttcAr as number(30,2)) as montantttcAr,
    cast(bcf.montantremise as number(30,2)) as montantremise,cast(bcf.MONTANTTVA as number(30,2)) as MONTANTTVA
FROM BONDECOMMANDE_CLIENT bc
         LEFT JOIN CLIENT c ON c.id = bc.IDCLIENT
         LEFT JOIN MODEPAIEMENT m ON m.id = bc.MODEPAIEMENT
         LEFT JOIN MAGASIN2 m2 ON m2.id = bc.IDMAGASIN
         left join vente_origine vo on vo.IDORIGINE=bc.id
         left join REPRESENTANT r on bc.IDREPRESENTANT = r.ID
        left join BCClientFille_GrpMontant bcf on bcf.IDBC=bc.ID;

