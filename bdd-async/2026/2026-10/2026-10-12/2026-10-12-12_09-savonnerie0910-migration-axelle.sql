CREATE TABLE PAIEMENT_SALAIRE 
(	ID VARCHAR2(50) PRIMARY KEY, 
	IDEDITION VARCHAR2(50), 
	IDPERSONNEL VARCHAR2(50), 
	MONTANT NUMBER(18,2), 
	IDMODEPAIEMENT VARCHAR2(50), 
	DATY DATE, 
	DATEPAIEMENT DATE, 
	ETAT NUMBER, 
	NUMEROCOMPTE VARCHAR2(255)
);

CREATE SEQUENCE SEQ_PAIEMENT_SALAIRE INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999 NOCYCLE CACHE 20 NOORDER; 

CREATE FUNCTION GETSEQPAIEMENTSALAIRE
    RETURN NUMBER
    IS
BEGIN
    RETURN SEQ_PAIEMENT_SALAIRE.NEXTVAL;
END;


ALTER TABLE PERIODEPAIE ADD DATEPAIEMENT DATE;

CREATE VIEW PAIEMENT_SALAIRE_LIB (ID, IDEDITION, IDPERSONNEL, MONTANT, IDMODEPAIEMENT, DATY, DATEPAIEMENT, ETAT, NOMPERSONNEL, MATRICULE, BU, BULIB, UNITELIB, IDSECTIONLIB, DIRECTIONLIB, MODEPAIEMENTLIB, ETATLIB, IDSOCIETELIB, IDSOCIETE) AS 
  SELECT
    ps.ID,
    ps.IDEDITION,
    ps.IDPERSONNEL,
    ps.GAIN as montant,
    pip.MODE_PAIEMENT as idModePaiement,
    CURRENT_DATE AS DATY,
    periode.DATEPAIEMENT,
    ps.ETAT,

    log.nom || ' ' || log.prenom AS nomPersonnel,

    pip.matricule,
    pip.unite AS bu,
    bu.val AS buLib,
    lu.val as uniteLib,
    ls.libelle AS idSectionLib,
    ld.val AS directionLib,
    mp.val AS modePaiementLib,

    CASE
        WHEN ps.etat = 1 THEN '<span style=color: blue;>IMPAY&Eacute;</span>'
        WHEN ps.etat = -1 THEN '<span style=color: red;>REJET&Eacute;</span>'
        WHEN ps.etat = 7 THEN '<span style=color: yellow;>OV G&Eacute;N&Eacute;R&Eacute;</span>'
        WHEN ps.etat = 11 THEN '<span style=color: green;>PAY&Eacute;</span>'
        WHEN ps.etat = 0 THEN '<span style=color: green;>ANNUL&Eacute;</span>'
        ELSE 'INCONNU'
        END AS etatLib,
    sc.val as idSocieteLib,
    sc.id as idSociete

FROM PAIE_EDITION ps
         LEFT JOIN LOG_PERSONNEL log
                   ON log.id = ps.idPersonnel
         LEFT JOIN PAIE_INFO_PERSONNEL pip
                   ON pip.id = ps.idPersonnel
         LEFT JOIN BUSINESS_UNITE bu
                   ON bu.id = pip.unite
         LEFT JOIN MODEPAIEMENT mp
                   ON mp.id = ps.MODEPAIEMENT
         LEFT JOIN LOG_UNITE lu ON lu.id = pip.unite
         LEFT JOIN log_direction ld ON ld.id = log.direction
         LEFT JOIN log_service ls ON ls.id = pip.idSection
         LEFT JOIN PAIE_EDITIONMOISANNEE paie ON paie.id = ps.IDEDITION
         LEFT JOIN PERIODEPAIE periode ON periode.mois = paie.mois and periode.ANNEE = paie.ANNEE
         LEFT JOIN SOCIETE sc ON sc.id = pip.IDSOCIETE
where ps.IDELEMENTPAIE='PR000210A';

CREATE VIEW PAIEMENT_SALAIRE_IMPAYE (ID, IDEDITION, IDPERSONNEL, MONTANT, IDMODEPAIEMENT, DATY, DATEPAIEMENT, ETAT, NOMPERSONNEL, MATRICULE, BU, BULIB, MODEPAIEMENTLIB, ETATLIB) AS 
  SELECT ID,IDEDITION,IDPERSONNEL,MONTANT,IDMODEPAIEMENT,DATY,DATEPAIEMENT,ETAT,NOMPERSONNEL,MATRICULE,BU,BULIB,MODEPAIEMENTLIB,ETATLIB
FROM PAIEMENT_SALAIRE_LIB
WHERE etat = 1;

CREATE VIEW PAIEMENT_SALAIRE_OVGENERE (ID, IDEDITION, IDPERSONNEL, MONTANT, IDMODEPAIEMENT, DATY, DATEPAIEMENT, ETAT, NOMPERSONNEL, MATRICULE, BU, BULIB, MODEPAIEMENTLIB, ETATLIB) AS 
  SELECT ID,IDEDITION,IDPERSONNEL,MONTANT,IDMODEPAIEMENT,DATY,DATEPAIEMENT,ETAT,NOMPERSONNEL,MATRICULE,BU,BULIB,MODEPAIEMENTLIB,ETATLIB
FROM PAIEMENT_SALAIRE_LIB
WHERE etat = 7;

CREATE VIEW PAIEMENT_SALAIRE_PAYE (ID, IDEDITION, IDPERSONNEL, MONTANT, IDMODEPAIEMENT, DATY, DATEPAIEMENT, ETAT, NOMPERSONNEL, MATRICULE, BU, BULIB, MODEPAIEMENTLIB, ETATLIB) AS 
  SELECT ID,IDEDITION,IDPERSONNEL,MONTANT,IDMODEPAIEMENT,DATY,DATEPAIEMENT,ETAT,NOMPERSONNEL,MATRICULE,BU,BULIB,MODEPAIEMENTLIB,ETATLIB
FROM PAIEMENT_SALAIRE_LIB
WHERE etat = 11;
