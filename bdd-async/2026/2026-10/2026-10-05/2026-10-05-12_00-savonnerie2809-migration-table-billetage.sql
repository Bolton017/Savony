CREATE TABLE BILLETAGE (
	ID VARCHAR2(255) PRIMARY KEY NOT NULL , 
	DESCE VARCHAR2(200), 
	NOMBRE NUMBER(30,0), 
	IDCLOTURE VARCHAR2(100), 
	CONSTRAINT FK_BILLETAGE_CLOTURE FOREIGN KEY (IDCLOTURE) REFERENCES CLOTURECAISSE (ID)
);

CREATE VIEW BILLETAGE_CPL AS 
  SELECT
	bg.id,
	bg.desce,
	bg.nombre,
	bl.val AS valeurBillet,
	bg.nombre * bl.val AS montant,
	bg.idcloture
FROM
	BILLETAGE bg
LEFT JOIN BILLET bl ON bl.id = bg.desce;
