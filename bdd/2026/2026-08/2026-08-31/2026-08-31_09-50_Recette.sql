CREATE VIEW RECETTE_MERE_LIB AS
SELECT
    rm.*,
    ai.LIBELLE as IDPRODUITLIB
FROM RECETTE_MERE rm
LEFT JOIN
    AS_INGREDIENTS ai ON rm.IDPRODUIT = ai.ID;

CREATE VIEW RECETTE_FILLE_LIB AS
SELECT
    rf.*,
    ai.LIBELLE as IDINGREDIENTLIB,
    au.VAL as IDUNITELIB
FROM RECETTE_FILLE rf
LEFT JOIN
    AS_INGREDIENTS ai ON rf.IDINGREDIENT = ai.ID
LEFT JOIN
    AS_UNITE au ON rf.IDUNITE = au.ID;