CREATE OR REPLACE FUNCTION getseqforfaitzoneclient
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT seqforfaitzoneclient.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;