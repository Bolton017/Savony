CREATE OR REPLACE  VIEW COMPTA_SOUSECRITURE_LETTRE (ID, NUMERO, COMPTE, JOURNAL, IDJOURNAL, ECRITURE, DATY, CREDIT, DEBIT, DATECOMPTABLE, EXERCICE, REMARQUE, ETAT, IDMERE, HORSEXERCICE, OD, ORIGINE, TIERS, LIBELLEPIECE, COMPTE_AUX, RAISONSOCIAL, FOLIO, LETTRAGE, ANALYTIQUE, IDVENTE, LETTRE, MONTANT,compte_auxlib) AS 
  SELECT
    lib.ID,lib.NUMERO,lib.COMPTE,lib.JOURNAL,lib.IDJOURNAL,lib.ECRITURE,lib.DATY,lib.CREDIT,lib.DEBIT,lib.DATECOMPTABLE,lib.EXERCICE,lib.REMARQUE,lib.ETAT,lib.IDMERE,lib.HORSEXERCICE,lib.OD,lib.ORIGINE,lib.TIERS,lib.LIBELLEPIECE,lib.COMPTE_AUX,lib.RAISONSOCIAL,lib.FOLIO,lib.LETTRAGE,lib.ANALYTIQUE,
    COALESCE(mtc.IDORIGINE, ecr.IDOBJET) AS IDVENTE,CLTR.lettre,
     CASE
        WHEN NVL(lib.DEBIT, 0) = 0 THEN lib.CREDIT
        WHEN NVL(lib.CREDIT, 0) = 0 THEN lib.DEBIT
        ELSE lib.DEBIT - lib.CREDIT
    END AS MONTANT,
    lib.RAISONSOCIAL AS compteaux_lib
FROM
    COMPTA_SOUSECRITURE_LIB lib
        JOIN COMPTA_ECRITURE ecr ON lib.IDMERE = ecr.ID
        LEFT JOIN MOUVEMENTCAISSE mtc ON ecr.IDOBJET = mtc.ID
        LEFT JOIN compta_lettrage cltr on cltr.id=lib.lettrage
order by IDVENTE DESC
 
;