CREATE OR REPLACE VIEW TRANSFERTSTOCKCPL AS 
  SELECT
    t.ID ,
    t.DESIGNATION ,
    t.IDMAGASINDEPART ,
    m.VAL AS IDMAGASINDEPARTLIB,
    t.IDMAGASINARRIVE ,
    m2.VAL AS IDMAGASINARRIVELIB,
    t.DATY ,
    t.ETAT ,
    t.idof,
    CASE
        WHEN t.ETAT = 0
            THEN 'ANNULÉE'
        WHEN t.ETAT = 1
            THEN 'CRÉÉE'
        WHEN t.ETAT = 11
            THEN 'VISÉE'
        END AS ETATLIB,
    t.iddemande,
    m.IDDEPARTEMENT AS IDDEPARTEMENTDEPART,
    s.LIBELLE AS idDepartementLibDepart,
    m2.IDDEPARTEMENT AS IDDEPARTEMENTARRIVE,
    s2.LIBELLE AS idDepartementLibArrive,
    CAST(tgm.montantQuantite AS NUMBER(30,2)) AS montantQuantite
FROM TRANSFERTSTOCK t
         LEFT JOIN MAGASINPOINT m ON m.ID = t.IDMAGASINDEPART
         LEFT JOIN MAGASINPOINT m2 ON m2.ID = t.IDMAGASINARRIVE
         LEFT JOIN SERVICE s ON m.IDDEPARTEMENT = s.ID
         LEFT JOIN SERVICE s2 ON m2.IDDEPARTEMENT = s2.ID
         LEFT JOIN TRANSTOCKDETAILSGROUPEMERE tgm ON tgm.IDTRANSFERTSTOCK = t.id;
