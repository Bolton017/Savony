create sequence SEQACCIDENT
      minvalue 1
      maxvalue 999999999999
      start with 1
      increment by 1
      cache 20;

create sequence SEQTYPEACCIDENT
      minvalue 1
      maxvalue 999999999999
      start with 1
      increment by 1
      cache 20;

create sequence SEQGRAVITEACCIDENT
      minvalue 1
      maxvalue 999999999999
      start with 1
      increment by 1
      cache 20;

create sequence SEQLIEUACCIDENTTRAVAIL
      minvalue 1
      maxvalue 999999999999
      start with 1
      increment by 1
      cache 20;

--Creer fonctions : 
--GETSEQACCIDENT
--GETSEQTYPEACCIDENT
--GETSEQGRAVITEACCIDENT
--GETSEQACCIDENTTRAVAIL



      
      

CREATE OR REPLACE FUNCTION GETSEQACCIDENT
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQACCIDENT.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END; 

