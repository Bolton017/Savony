
CREATE OR REPLACE VIEW COMMENTAIREOF_LIB AS
SELECT c.ID,
       c.IDOBJET,
       c.VAL,
       c.IDPERSONNEL,
       p.NOMUSER
FROM COMMENTAIREOF c
LEFT JOIN UTILISATEUR p
       ON TO_CHAR(p.REFUSER) = TRIM(c.IDPERSONNEL);

