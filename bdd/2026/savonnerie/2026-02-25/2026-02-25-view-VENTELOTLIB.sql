CREATE OR REPLACE  VIEW "VENTELOTLIB" ("ID", "DESIGNATION", "IDMAGASIN", "IDMAGASINLIB", "DATY", "REMARQUE", "ETAT", "ETATLIB", "MONTANTTOTAL", "IDDEVISE", "IDCLIENT", "IDCLIENTLIB", "MONTANTTVA", "MONTANTTTC", "MONTANTTTCAR", "MONTANTPAYE", "MONTANTRESTE", "AVOIR", "TAUXDECHANGE", "MONTANTREVIENT", "MARGEBRUTE", "IDRESERVATION", "DATYPREVU", "REFERENCEFACTURE", "MONTANTREMISE", "MONTANT", "MOIS", "ANNEE", "POIDS", "COLIS", "MODEPAIEMENT", "MODEPAIEMENTLIB", "FRAISLIVRAISON", "MODELIVRAISON", "MODELIVRAISONLIB", "RESTE", "IDPROVINCE", "PROVINCELIB", "IDORIGINE", "FRAIS", "REFERENCEFACT", "NUMEROFACTURE", "LIEULIVRAISON", "DATELIVRAISON", "UPDATED_AT", "IDLOT", "IDPRODUIT", "IDEQUIPE", "DATYLOT", "IDEQUIPELIB", "IDPRODUITLIB", "REMARQUELOT") AS 
  SELECT
    v.ID,
    v.DESIGNATION,
    v.IDMAGASIN,
    v.IDMAGASINLIB,
    v.DATY,
    v.REMARQUE,
    v.ETAT,
    v.ETATLIB,
    v.MONTANTTOTAL,
    v.IDDEVISE,
    v.IDCLIENT,
    v.IDCLIENTLIB,
    v.MONTANTTVA,
    v.MONTANTTTC,
    v.MONTANTTTCAR,
    v.MONTANTPAYE,
    v.MONTANTRESTE,
    v.AVOIR,
    v.TAUXDECHANGE,
    v.MONTANTREVIENT,
    v.MARGEBRUTE,
    v.IDRESERVATION,
    v.DATYPREVU,
    v.REFERENCEFACTURE,
    v.MONTANTREMISE,
    v.MONTANT,
    v.MOIS,
    v.ANNEE,
    v.POIDS,
    v.COLIS,
    v.MODEPAIEMENT,
    v.MODEPAIEMENTLIB,
    v.FRAISLIVRAISON,
    v.MODELIVRAISON,
    v.MODELIVRAISONLIB,
    v.RESTE,
    v.IDPROVINCE,
    v.PROVINCELIB,
    v.IDORIGINE,
    v.FRAIS,
    v.REFERENCEFACT,
    v.NUMEROFACTURE,
    v.LIEULIVRAISON,
    v.DATELIVRAISON,
    v.UPDATED_AT,
    l.ID AS IDLOT,
    l.IDPRODUIT,
    l.IDEQUIPE,
    l.DATY AS DATYLOT,
    l.IDEQUIPELIB,
    l.IDPRODUITLIB,
    l.REMARQUE AS REMARQUELOT
FROM LOTLIB l
LEFT JOIN mvtstockfilleLib mvtf ON mvtf.IDLOT = l.ID
LEFT JOIN AS_BONDELIVRAISON_CLIENT bl ON bl.ID = mvtf.IDOBJET
LEFT JOIN VENTE_CPL v ON v.ID = bl.IDVENTE;