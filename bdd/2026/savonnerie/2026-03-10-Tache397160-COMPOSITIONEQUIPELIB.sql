ALTER TABLE COMPOSITIONEQUIPE
    ADD idPoste VARCHAR(255);

CREATE OR REPLACE VIEW COMPOSITIONEQUIPELIB AS
SELECT
    C.*,
    p.NOM as idPersonnelLib,
    e.VAL as idEquipeLib
FROM COMPOSITIONEQUIPE c
         LEFT JOIN LOG_PERSONNEL_V2 p ON p.ID = c.IDPERSONNEL
         LEFT JOIN EQUIPE E ON E.ID = C.IDEQUIPE;
