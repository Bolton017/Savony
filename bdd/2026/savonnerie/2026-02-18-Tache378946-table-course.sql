CREATE TABLE COURSE
(
    ID              VARCHAR2(250) NOT NULL PRIMARY KEY,
    IDVEHICULE      VARCHAR2(250),
    IDCHAUFFEUR     VARCHAR2(250),
    DATY            DATE,
    REMARQUE        VARCHAR2(2000),
    ETAT            NUMBER
);

CREATE SEQUENCE seqCourse;

CREATE OR REPLACE FUNCTION getSeqCourse 
RETURN NUMBER 
IS 
    retour NUMBER;
BEGIN
    SELECT seqCourse.NEXTVAL
    INTO retour
    FROM DUAL;
    
    RETURN retour;
END;

CREATE TABLE COURSEFILLE
(
    ID              VARCHAR2(250) NOT NULL PRIMARY KEY,
    IDMERE          VARCHAR2(250) REFERENCES COURSE(ID),
    IDOBJET         VARCHAR2(250),
    DATEDEPART      DATE,
    HEUREDEPART     VARCHAR2(50),
    DATEARRIVEE     DATE,
    HEUREARRIVEE    VARCHAR2(50),
    IDPERSONNEL     VARCHAR2(250),
    REMARQUE        VARCHAR2(2000),
    ETAT            NUMBER
);

CREATE SEQUENCE seqCourseFille;

CREATE OR REPLACE FUNCTION getSeqCourseFille 
RETURN NUMBER 
IS 
    retour NUMBER;
BEGIN
    SELECT seqCourseFille.NEXTVAL
    INTO retour
    FROM DUAL;
    
    RETURN retour;
END;