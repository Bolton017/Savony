CREATE TABLE SEMAINECARBURANT
(
    ID              VARCHAR2(250) NOT NULL PRIMARY KEY,
    NUMEROSEMAINE   NUMBER,
    DATY            DATE,
    MONTANT         NUMBER(30,2),
    PERSONNE        VARCHAR2(250)
);

CREATE SEQUENCE seqSemaineCarburant;


CREATE OR REPLACE FUNCTION getSeqSemaineCarburant 
RETURN NUMBER 
IS 
    retour NUMBER;
BEGIN
    SELECT seqSemaineCarburant.NEXTVAL
    INTO retour
    FROM DUAL;
    
    RETURN retour;
END;

CREATE OR REPLACE VIEW GENERATIONCARBURANT AS
SELECT 
    CAST(NULL AS VARCHAR2(250)) AS ID,
    CAST(NULL AS VARCHAR2(250)) AS DEPARTEMENT,
    CAST(NULL AS VARCHAR2(250)) AS PERSONNE,
    CAST(NULL AS NUMBER) AS SEMAINE,
    CAST(NULL AS NUMBER) AS ANNEE,
    CAST(NULL AS NUMBER) AS NBJOUR
FROM DUAL
WHERE 1 = 0;