CREATE OR REPLACE VIEW "POINTAGE_LIB" AS
SELECT
    p.ID,
    p.IDPERSONNEL,
    p.direction,
    p.ANNEE,
    p.MOIS,
    p.HEURENORMAL,
    p.HEURESUPFERIE,
    p.HEURESUPNORMAL,
    p.HEURESUPNUIT,
    p.HEURESUPWEEKEND,
    p.ABSENCE,
    p.DATY,
    p.ETAT,
    ld.VAL AS directionLib,
    TO_CHAR(
            TO_DATE(TO_CHAR(p.mois, 'FM00'), 'MM'),
            'FMMonth',
            'NLS_DATE_LANGUAGE=FRENCH'
    ) AS moisLib,
    ec.MATRICULE ,
    ec.nom || ' ' || ec.PRENOM AS nomPersonnel
FROM POINTAGE p
         LEFT JOIN LOG_DIRECTION ld ON ld.id = p.DIRECTION
         LEFT JOIN EMPLOYE_COMPLET ec ON ec.id = p.IDPERSONNEL
;

