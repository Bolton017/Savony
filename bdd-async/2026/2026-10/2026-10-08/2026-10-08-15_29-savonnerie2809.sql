CREATE OR REPLACE  VIEW PERSONNEL_BU (ID, PERMIS_CONDUIRE, CHEMIN_PERMIS, REMARQUE, ID_PERS, NOM, PRENOM, DATE_NAISSANCE, IDSEXE, SEXE, NUMERO_CIN, DATE_CIN, DATE_DUPL_CIN, NATIONALITE, ADRESSE, FOKOTANY, ACTE_NAISSANCE, DIRECTION, SERVICE, REFUSER, IDSUP, IDHIERARCHIE, CHEMINIMAGE, IDCIVILITE, MERE, PERE, TELEPHONE, NOMDUSAGE, ADRESSE2, COMMUNE, PAYS, MATRICULE, IDDEPARTEMENT, TYPECONTRAT, UNITE, DEPARTEMENTLIB, BULIB, TYPECONTRATLIB, IDSECTION, IDSECTIONLIB) AS 
  SELECT
    log.ID,log.PERMIS_CONDUIRE,log.CHEMIN_PERMIS,log.REMARQUE,log.ID_PERS,log.NOM,log.PRENOM,log.DATE_NAISSANCE,
    log.SEXE AS idSexe,
    CASE
        WHEN log.SEXE = '0' THEN 'F'
        WHEN log.SEXE = '1' THEN 'M'
        ELSE log.SEXE
        END AS SEXE,
    log.NUMERO_CIN,log.DATE_CIN,log.DATE_DUPL_CIN,log.NATIONALITE,log.ADRESSE,log.FOKOTANY,log.ACTE_NAISSANCE,log.DIRECTION,log.SERVICE,log.REFUSER,log.IDSUP,log.IDHIERARCHIE,log.CHEMINIMAGE,log.IDCIVILITE,log.MERE,log.PERE,log.TELEPHONE,log.NOMDUSAGE,log.ADRESSE2,log.COMMUNE,log.PAYS,
    pip.matricule,
    pip.iddepartement,
    pip.typecontrat,
    pip.unite,
    dep.val as departementLib,
    bu.val as buLib,
    tc.val as typeContratLib,
    pip.idSection,
    service.LIBELLE as idSectionLib
FROM LOG_PERSONNEL log
         LEFT JOIN PAIE_INFO_PERSONNEL pip ON pip.id = log.id
         LEFT JOIN DEPARTEMENT dep ON dep.id = pip.IDDEPARTEMENT
         LEFT JOIN BUSINESS_UNITE bu ON bu.id = pip.idBu
         LEFT JOIN TYPE_CONTRAT tc ON tc.id = pip.typecontrat
         LEFT JOIN section sec ON sec.id = pip.idSection
         LEFT JOIN log_service service ON service.id = log.SERVICE

 
 
 
 ;


CREATE OR REPLACE  VIEW PERSONNEL_BU_FIN_CONGE (ID, PERMIS_CONDUIRE, CHEMIN_PERMIS, REMARQUE, ID_PERS, NOM, PRENOM, DATE_NAISSANCE, SEXE, NUMERO_CIN, DATE_CIN, DATE_DUPL_CIN, NATIONALITE, ADRESSE, FOKOTANY, ACTE_NAISSANCE, DIRECTION, SERVICE, REFUSER, IDSUP, IDHIERARCHIE, CHEMINIMAGE, IDCIVILITE, MERE, PERE, TELEPHONE, NOMDUSAGE, ADRESSE2, COMMUNE, PAYS, MATRICULE, IDDEPARTEMENT, TYPECONTRAT, UNITE, DEPARTEMENTLIB, BULIB, TYPECONTRATLIB, SEXELIB, CODE_DR, IDCATEGORIE, CTG, INDICEGRADE, INDICE_FONCTIONNEL, STATUT, CATEGORIEVAL, CTGVAL, NUMERO_CNAPS, NUMERO_OSTIE, TEMPORAIRE, DROIT, PRIE, RESTECONGE, DIRECTIONLIB, IDSECTION, IDSECTIONLIB, UNITELIB, IDSOCIETE, IDSOCIETELIB, ETAT, ETATLIB, MODE_PAIEMENT, MODEPAIEMENTLIB, CODE_BANQUE, CODE_AGENCE_BANQUE, BANQUE_NUMERO_COMPTE, BANQUE_COMPTE_CLE, SERVICELIB) AS 
  SELECT
    l.ID,l.PERMIS_CONDUIRE,l.CHEMIN_PERMIS,l.REMARQUE,l.ID_PERS,l.NOM,l.PRENOM,l.DATE_NAISSANCE,l.SEXE,l.NUMERO_CIN,l.DATE_CIN,l.DATE_DUPL_CIN,l.NATIONALITE,l.ADRESSE,l.FOKOTANY,l.ACTE_NAISSANCE,l.DIRECTION,l.SERVICE,l.REFUSER,l.IDSUP,l.IDHIERARCHIE,l.CHEMINIMAGE,l.IDCIVILITE,l.MERE,l.PERE,l.TELEPHONE,l.NOMDUSAGE,l.ADRESSE2,l.COMMUNE,l.PAYS,l.MATRICULE,l.IDDEPARTEMENT,l.TYPECONTRAT,l.UNITE,l.DEPARTEMENTLIB,l.BULIB,l.TYPECONTRATLIB,
    sex.desce AS sexeLib,
    s.code_dr,
    paie.idcategorie,
    paie.ctg,
    paie.indicegrade,
    paie.indice_fonctionnel,
    paie.statut,
    c.taux AS categorieval,
    '' AS ctgval,
    paie.numero_cnaps,
    paie.numero_ostie,
    CASE
        WHEN paie.temporaire = -1 THEN 'Temporaire'
        WHEN paie.temporaire = 0 THEN 'Permanent'
        WHEN paie.temporaire = 1 THEN 'Cadre'
        ELSE NULL
        END AS temporaire,
    CAST(NVL(sc.PLUS , 0) AS NUMBER(30, 2)) AS droit ,
    CAST(NVL(sp.CONGEPRIS , 0) AS NUMBER(30, 2)) AS prie,
    CAST(NVL(sc.SOLDE, 0) AS NUMBER(30, 2)) AS resteconge,
    d.val as directionLib,
    l.idSection,
    l.idSectionLib,
    lu.val as uniteLib,
    paie.IDSOCIETE,
    soc.val as IDSOCIETELIB,
    paie.etat,
    CASE
        WHEN paie.etat < 1 THEN 'Licencié'
        WHEN paie.etat = 1 THEN 'Créé'
        WHEN paie.etat = 7 THEN 'Désactivé'
        WHEN paie.etat = 11 THEN 'Actif'
        ELSE NULL
        END AS etatLib,
    paie.MODE_PAIEMENT,
    md.val as modePaiementLib,
    paie.CODE_BANQUE,
    paie.CODE_AGENCE_BANQUE,
    paie.BANQUE_NUMERO_COMPTE,
    paie.BANQUE_COMPTE_CLE,
    s.LIBELLE AS serviceLib
FROM PERSONNEL_BU l
         LEFT JOIN log_service s ON l.service = s.id
         LEFT JOIN paie_info_personnel paie ON paie.id = l.id
         LEFT JOIN sexe sex ON l.sexe = sex.id
         LEFT JOIN log_direction d ON d.id = l.direction
         LEFT JOIN paie_categorie c ON c.id = paie.idcategorie
         LEFT JOIN SOLDECONGEPRIS_PERS sp ON l.id = sp.id
         LEFT JOIN SOLDECONGE_PERS sc ON l.id = sc.idPersonnel
         LEFT JOIN departement dp ON paie.idDepartement = dp.id
         LEFT JOIN LOG_UNITE lu ON lu.id = l.unite
         LEFT JOIN Societe soc ON soc.id = paie.IDSOCIETE
         LEFT JOIN MODEPAIEMENT md ON md.id = paie.MODE_PAIEMENT
 
 ;

