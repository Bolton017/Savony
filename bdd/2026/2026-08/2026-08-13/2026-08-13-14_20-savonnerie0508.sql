ALTER TABLE AS_INGREDIENTS ADD COMPTE_SORTIE_STOCK VARCHAR2(255);
ALTER TABLE AS_INGREDIENTS ADD COMPTE_STOCK VARCHAR2(255);

CREATE VIEW MVTSTOCKFILLEGRP AS
SELECT
    f.IDMVTSTOCK,
    SUM(f.ENTREE * f.PU) AS entree,
    SUM(f.SORTIE * f.PU) AS SORTIE,
    ing.compte_stock,
    compte_sortie_stock
FROM MVTSTOCKFILLE f
         LEFT JOIN AS_INGREDIENTS ing ON ing.ID = f.IDPRODUIT
GROUP BY f.IDMVTSTOCK, ing.compte_stock,compte_sortie_stock
;


CREATE VIEW MVTSTOCKFILLEGRPVARIATION AS
SELECT
    f.IDMVTSTOCK,
    SUM(f.ENTREE * f.PU) AS entree,
    SUM(f.SORTIE * f.PU) AS SORTIE,
    null as compte_stock,
    ing.compte_sortie_stock
FROM MVTSTOCKFILLE f
         LEFT JOIN AS_INGREDIENTS ing ON ing.ID = f.IDPRODUIT
GROUP BY f.IDMVTSTOCK, ing.compte_sortie_stock
;

