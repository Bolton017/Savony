i.ID,i.DATY,i.DESIGNATION,i.IDMAGASIN,i.IDMAGASINLIB,i.ETAT,i.ETATLIB,i.HEURE, i.IDDEPARTEMENT, i.IDDEPARTEMENTLIB
FROM INVENTAIRELIB i 
