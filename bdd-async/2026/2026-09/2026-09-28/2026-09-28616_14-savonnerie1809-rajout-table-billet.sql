CREATE TABLE billet 
(
	id VARCHAR2(100) PRIMARY KEY,
	val VARCHAR2(255),
	desce VARCHAR2(255)
);

CREATE SEQUENCE SEQBILLET INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER;

CREATE OR REPLACE FUNCTION GETSEQBILLET
     RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT SEQBILLET.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;

