CREATE OR REPLACE VIEW TRANSFERTSTOCKANOMALIE AS 
  SELECT DISTINCT t.ID,t.DESIGNATION,t.IDMAGASINDEPART,t.IDMAGASINDEPARTLIB,t.IDMAGASINARRIVE,t.IDMAGASINARRIVELIB,t.DATY,t.ETAT,t.IDOF,t.ETATLIB,t.IDDEMANDE,
  t.IDDEPARTEMENTDEPART,t.idDepartementLibDepart,t.IDDEPARTEMENTARRIVE,t.idDepartementLibArrive
FROM TRANSFERTSTOCKCPL t
JOIN MVTSTOCKLIB m1 ON m1.IDTRANSFERT = t.ID AND m1.ETAT = 11
JOIN MVTSTOCKLIB m2 ON m2.IDTRANSFERT = t.ID AND m2.ETAT < 11;