CREATE OR REPLACE VIEW "COURSELIB" ("ID", "IDVEHICULE", "IDCHAUFFEUR", "DATY", "REMARQUE", "ETAT", "ETATLIB", "IDVEHICULELIB", "IDCHAUFFEURLIB") AS
SELECT
    c.ID,
    c.IDVEHICULE,
    c.IDCHAUFFEUR,
    c.DATY,
    c.REMARQUE,
    c.ETAT,
    CASE
        WHEN c.ETAT = 1
            THEN 'CRÉÉE'
        WHEN c.ETAT = 0
            THEN 'ANNULÉE'
        WHEN c.ETAT = 7  THEN 'EN COURS DE LIVRAISON'
        WHEN c.ETAT = 11
            THEN 'TERMINÉE'
        END AS ETATLIB,
    v.LIBELLE AS IDVEHICULELIB,
    ch.NOM  AS IDCHAUFFEURLIB
FROM COURSE c
         LEFT JOIN AS_INGREDIENT_MAINTENANCE v ON v.id = c.IDVEHICULE
         LEFT JOIN AS_INGREDIENTS ai ON ai.id = v.IDINGREDIENT
         LEFT JOIN CHAUFFEUR ch ON ch.ID = c.IDCHAUFFEUR

;

CREATE OR REPLACE VIEW "COURSEFILLELIB" AS
SELECT
    cf.ID,
    cf.IDOBJET,
    cf.DATEDEPART,
    cf.HEUREDEPART,
    cf.DATEARRIVEE,
    cf.HEUREARRIVEE,
    cf.IDPERSONNEL,
    cf.REMARQUE,
    cf.idmere,
    cf.ETAT,
    (lp.NOM || ' ' || lp.PRENOM) AS IDPERSONNELLIB,
    CASE
        WHEN cf.ETAT = 1
            THEN 'CRÉÉE'
        WHEN cf.ETAT = 0
            THEN 'ANNULÉE'
        WHEN cf.ETAT = 7  THEN 'EN COURS DE LIVRAISON'
        WHEN cf.ETAT = 11
            THEN 'TERMINÉE'
        END AS ETATLIB
FROM COURSEFILLE cf
         LEFT JOIN LOG_PERSONNEL lp ON lp.ID = cf.IDPERSONNEL
         LEFT JOIN COURSE c ON c.ID = cf.IDMERE

;

