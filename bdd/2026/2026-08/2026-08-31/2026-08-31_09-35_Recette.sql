


CREATE TABLE RECETTE_MERE
(
    ID VARCHAR2(255) CONSTRAINT  RECETTE_MERE_PKEY PRIMARY KEY,
    IDPRODUIT VARCHAR2(255) CONSTRAINT  RECETTE_MERE_IDPRODUIT_FK REFERENCES AS_INGREDIENTS(ID),
    DATY DATE,
    NOMRECETTE VARCHAR2(255),
    VERSION VARCHAR2(255)
);

CREATE TABLE RECETTE_FILLE
(
    ID VARCHAR2(255) CONSTRAINT  RECETTE_F_PKEY PRIMARY KEY,
    IDMERE VARCHAR2(255) CONSTRAINT  RECETTE_F_IDRECETTE_MERE_FK REFERENCES RECETTE_MERE(ID),
    IDINGREDIENT VARCHAR2(255) CONSTRAINT  RECETTE_F_IDINGREDIENT_FK REFERENCES AS_INGREDIENTS(ID),
    IDUNITE VARCHAR2(255) CONSTRAINT  RECETTE_F_IDUNITE_FK REFERENCES AS_UNITE(ID),
    QTE NUMBER(10,2)
);


create sequence SEQRECETTE_MERE
    minvalue 1
    maxvalue 999999999999
    start with 1
    increment by 1
    cache 20;



CREATE OR REPLACE FUNCTION GETSEQRECETTE_MERE
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
    SELECT SEQRECETTE_MERE.NEXTVAL INTO retour FROM DUAL;

    RETURN retour;
END;


create sequence SEQRECETTE_FILLE
    minvalue 1
    maxvalue 999999999999
    start with 1
    increment by 1
    cache 20;



CREATE OR REPLACE FUNCTION GETSEQRECETTE_FILLE
    RETURN NUMBER
    IS
    retour   NUMBER;
BEGIN
    SELECT SEQRECETTE_FILLE.NEXTVAL INTO retour FROM DUAL;

    RETURN retour;
END;


