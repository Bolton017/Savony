CREATE TABLE critere 
   (	"ID" VARCHAR2(255), 
	"VAL" VARCHAR2(255), 
	"DESCE" VARCHAR2(255), 
	 CONSTRAINT "critere_pk" PRIMARY KEY ("ID")
  );


CREATE SEQUENCE seqcritere INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999 NOCYCLE CACHE 20 NOORDER 

CREATE OR REPLACE FUNCTION getseqcritere
   RETURN NUMBER
IS
   retour   NUMBER;
BEGIN
   SELECT seqcritere.NEXTVAL INTO retour FROM DUAL;

   RETURN retour;
END;
 
 
 
