JOIN LOG_PERSONNEL lp ON lp.ID_PERS  = pe.idpersonnel
JOIN PAIE_INFO_PERSONNEL pip ON pe.IDPERSONNEL = pip.id
WHERE pe.mois = 7 AND pe.ANNEE = 2025 ORDER BY pe.idpersonnel ASC;

