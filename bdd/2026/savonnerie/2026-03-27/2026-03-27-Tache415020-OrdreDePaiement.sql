create table OPFACTURE (
    ID VARCHAR2(255) primary key,
    IDOP      VARCHAR2(255),
    IDFACTURE VARCHAR2(255),
    MONTANT   NUMBER(25, 2),
    DATY      DATE,
    ETAT      NUMBER(10)
);

create table ORDREDEPAIEMENT (
    ID VARCHAR2(255) primary key,
    IDFACTS      VARCHAR2(4000),
    DATY         DATE,
    MONTANT      NUMBER(25, 2),
    REMARQUE     VARCHAR2(4000),
    ETAT         NUMBER(10),
    NUMEROOP     VARCHAR2(255),
    MODEPAIEMENT VARCHAR2(150),
    TIERS        VARCHAR2(255),
    IDUSER       VARCHAR2(255),
    FOREIGN KEY (MODEPAIEMENT) references MODEPAIEMENT(id)
);

CREATE SEQUENCE SEQ_OrdrePaiement INCREMENT BY 1 MINVALUE 1 MAXVALUE 999999999999999999999999999 NOCYCLE CACHE 20 NOORDER ;

CREATE OR REPLACE FUNCTION getSeqOrdrePaiement
    RETURN NUMBER IS
    retour NUMBER;
BEGIN
    SELECT SEQ_OrdrePaiement.nextval INTO retour FROM dual;
    return retour;
END;



