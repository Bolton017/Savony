create or replace view AS_INGREDIENT_VENTE_LIB as
select ing."ID",
       concat(concat(ing.LIBELLE, ' '), ing.PARFUMS) as LIBELLE,
       ing."SEUIL",
       ing."UNITE",
       ing."QUANTITEPARPACK",
       ing."PU",
       ing."ACTIF",
       ing."PHOTO",
       ing."CALORIE",
       ing."DURRE",
       ing."COMPOSE",
       ing."CATEGORIEINGREDIENT",
       ing."IDFOURNISSEUR",
       ing."DATY",
       ing."QTELIMITE",
       ing."PV",
       ing."LIBELLEVENTE",
       ing."SEUILMIN",
       ing."SEUILMAX",
       ing."PUACHATUSD",
       ing."PUACHATEURO",
       ing."PUACHATAUTREDEVISE",
       ing."PUVENTEUSD",
       ing."PUVENTEEURO",
       ing."PUVENTEAUTREDEVISE",
       ing."ISVENTE",
       ing."ISACHAT",
       ing."COMPTE_VENTE",
       ing."COMPTE_ACHAT",
       ing."LIBELLEEXTACTE",
       ing."TVA",
       ing."FILEPATH",
       ing."RESTE",
       ing."TYPESTOCK",
       ing."REFPOST",
       ing."REFQUALIFICATION",
       ing."IDCHAMBRE",
       ing."ISPERISHABLE",
       ing."PV2",
       ing."IDMAGASIN",
       nvl(ting.PRIXUNITAIRE,ing.PV) AS PRIXUNITAIRE,
       TING.IDTYPECLIENT,
       tc.VAL                                        as idtypeclientlib,
       un.id                                         as idunite,
       un.VAL                                        as idunitelib,
       eq.POIDS,
       eq.QTE
from AS_INGREDIENTS ing
         left join TARIF_INGREDIENTS_MAX ting on ing.ID = TING.IDINGREDIENT
         left join AS_UNITE un on un.ID = TING.UNITE
         left join TYPECLIENT tc on tc.ID = TING.IDTYPECLIENT
         left join EQUIVALENCE eq on eq.IDPRODUIT = ting.IDINGREDIENT and eq.IDUNITE = ting.UNITE
        WHERE ing.CATEGORIEINGREDIENT = 'CAT008';
