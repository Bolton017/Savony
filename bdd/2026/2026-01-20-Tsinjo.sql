CREATE OR REPLACE VIEW CA_JOURNALIER_UNION AS
select cj.MONTANT,
       cj.ANNEE,
       cj.MOIS,
       cj.DATY
from ca_jour cj
union all
select cj.montant, annee, mois, daty
from ca_journalier cj;

CREATE OR REPLACE VIEW CA_JOURNALIER_UNION_GP AS
select sum(montant) as montant, annee, mois, daty from ca_journalier_union group by annee, mois, daty
;

CREATE OR REPLACE VIEW V_JOURS_2016_NOW AS
SELECT
    d AS DATY,
    EXTRACT(DAY FROM d) AS JOUR,
    CEIL((TO_CHAR(d, 'DD') + TO_CHAR(TRUNC(d, 'MM'), 'D') - 1) / 7) as semainemois,
    EXTRACT(MONTH FROM d) AS MOIS,
    EXTRACT(YEAR FROM d) AS ANNEE,
    TO_CHAR(d, 'D') as numerojoursemaine,
    TO_CHAR(d, 'Day', 'NLS_DATE_LANGUAGE=FRENCH') AS JOURLIB
FROM (
         SELECT TO_DATE('2025-05-01', 'YYYY-MM-DD') + LEVEL - 1 AS d
         FROM dual
             CONNECT BY LEVEL <= LAST_DAY(SYSDATE) - TO_DATE('2025-05-01', 'YYYY-MM-DD') + 1
     );

CREATE OR REPLACE VIEW CA_JOUR_DETAILS AS
select vj2n.DATY,
       vj2n.JOUR,
       vj2n.semainemois,
       vj2n.MOIS,
       vj2n.ANNEE,
       vj2n.JOURLIB,
       cast(nvl(cj.MONTANT, 0) as number(38, 2)) as montant,
       js.id as idjoursemaine,
       vj2n.numerojoursemaine
from V_JOURS_2016_now vj2n
         left join ca_journalier_union_gp cj on cj.DATY = vj2n.DATY
         left join joursemaine js on js.numsemaine = vj2n.semainemois and js.numjour = vj2n.numerojoursemaine;

CREATE OR REPLACE VIEW V_MOIS_ANNEE_DISTINCTS AS
SELECT
    EXTRACT(MONTH FROM dt) AS MOIS,
    EXTRACT(YEAR FROM dt) AS ANNEE,
    TRIM(TO_CHAR(dt, 'Month', 'NLS_DATE_LANGUAGE=FRENCH')) AS moislib
FROM (
         SELECT ADD_MONTHS(DATE '2025-05-01', LEVEL - 1) AS dt
         FROM dual
             CONNECT BY ADD_MONTHS(DATE '2025-05-01', LEVEL - 1) <= TRUNC(SYSDATE, 'MM')
     )
ORDER BY ANNEE, MOIS;