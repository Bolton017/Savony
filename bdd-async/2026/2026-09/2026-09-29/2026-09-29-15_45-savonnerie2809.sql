        NVL(fcpl.designation, '') || ' ' ||
        NVL(fcpl.reference, '') || ' ' ||
        NVL(fcpl.idfournisseurlib, '') || ' ' ||
        NVL(fcpl.idmodepaiementlib, '') || ' ' ||
        NVL(fcpl.idmagasinlib, '') || ' ' ||
        NVL(fcpl.devise, '') || ' ' ||
        NVL(fcpl.idbc, '') || ' ' ||
