CREATE VIEW V_DASH_MATERNITE_MOIS (MOIS, NOMBREDEPART) AS 
  SELECT
    TO_CHAR(DATEDEPARTTHEORIQUE, 'YYYY-MM') AS mois,
    COUNT(ID) AS nombreDepart
FROM
    V_MATERNITE_LIB
WHERE
    DATEDEPARTTHEORIQUE IS NOT NULL
GROUP BY
    TO_CHAR(DATEDEPARTTHEORIQUE, 'YYYY-MM')
ORDER BY
    TO_CHAR(DATEDEPARTTHEORIQUE, 'YYYY-MM') ASC;

CREATE VIEW V_DASH_MATERNITE_DUREE_GLB (ID, DUREEMOYENNEJOURS) AS 
  SELECT
    'Global' AS id,
    ROUND(AVG(DATERETOURTHEORIQUE - DATEDEPARTTHEORIQUE), 2) AS dureeMoyenneJours
FROM
    V_MATERNITE_LIB
WHERE
    DATEDEPARTTHEORIQUE IS NOT NULL
  AND DATERETOURTHEORIQUE IS NOT NULL;

CREATE VIEW V_DASH_MATERNITE_ECART_DATE (ID, IDPERSONNEL, IDPERSONNELLIB, DATEDEPARTTHEORIQUE, DATEDEPARTREEL, ECARTDEPARTJOURS, DATERETOURTHEORIQUE, DATERETOURAJUSTE, ECARTRETOURJOURS) AS 
  SELECT
    ID,
    IDPERSONNEL,
    IDPERSONNELLIB,
    DATEDEPARTTHEORIQUE,
    DATEDEPARTREEL,
    CASE
        WHEN DATEDEPARTREEL IS NOT NULL
        THEN DATEDEPARTREEL - DATEDEPARTTHEORIQUE
        ELSE NULL
    END AS ECARTDEPARTJOURS,
    DATERETOURTHEORIQUE,
    DATERETOURAJUSTE,
    CASE
        WHEN DATERETOURAJUSTE IS NOT NULL
        THEN DATERETOURAJUSTE - DATERETOURTHEORIQUE
        ELSE NULL
    END AS ECARTRETOURJOURS
FROM V_MATERNITE_LIB;








