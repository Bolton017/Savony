CREATE  VIEW COMPTA_ECRITURE_FICHE_V2
            ("ID", "DATY", "DATECOMPTABLE", "EXERCICE", "DESIGNATION", "REMARQUE", "ETAT", "HORSEXERCICE", "JOURNAL", "OD", "ORIGINE", "CREDIT", "DEBIT", "IDUSER", "PERIODE", "TRIMESTRE", "ANNEE", "IDOBJET", "LETTRAGE", "LIEN", "DATESAISIE", "DATEMODIF", "IDMODIFICATEUR", "IDMODIFICATEURLIB", "JOURNALLIB","JOURNALDESCE") AS
SELECT
    cef.ID,
    cef.DATY,
    cef.DATECOMPTABLE,
    cef.EXERCICE,
    cef.DESIGNATION,
    cef.REMARQUE,
    cef.ETAT,
    cef.HORSEXERCICE,
    cef.JOURNAL,
    cef.OD,
    cef.ORIGINE,
    cef.CREDIT,
    cef.DEBIT,
    cef.IDUSER,
    cef.PERIODE,
    cef.TRIMESTRE,
    cef.ANNEE,
    cef.IDOBJET,
    cef.LETTRAGE,
    cef.LIEN,
    cef.DATESAISIE,
    cef.DATEMODIF,
    cef.IDMODIFICATEUR,
    cef.IDMODIFICATEURLIB,
    cj.VAL AS JOURNALLIB,
    cj.DESCE AS JOURNALDESCE
FROM COMPTA_ECRITURE_FICHE cef
         LEFT JOIN COMPTA_JOURNAL cj ON cj.ID = cef.JOURNAL
;